<?php
// PhpAgent v2 - web entry point (local mode). Run: php -S localhost:8000 -t public
// Search-engine style: large search box, instant local suggestions, command
// chips, mode toggle lives on ai.php. No JavaScript framework, no CDN, no
// external assets, no API calls. GET and POST both work. All output escaped.
// The PHP session remembers the last topic so follow-ups like "example"
// resolve against it; the browser remembers recent/pinned topics in
// localStorage on localhost only.

declare(strict_types=1);

session_start();

require __DIR__ . '/../src/PhpAgent.php';
require __DIR__ . '/ui.php';

$agent = PhpAgent::create(__DIR__ . '/../data');
$query = trim((string) ($_REQUEST['q'] ?? ''));
$result = null;
if ($query !== '') {
    $lastTopic = isset($_SESSION['php_agent_last_topic']) ? (string) $_SESSION['php_agent_last_topic'] : null;
    $result = $agent->answer($query, $lastTopic);
    if (!empty($result['entry']['id'])) {
        $_SESSION['php_agent_last_topic'] = (string) $result['entry']['id'];
    } elseif (!empty($result['function']['name'])) {
        $_SESSION['php_agent_last_topic'] = 'fn:' . (string) $result['function']['name'];
    }
}

php_agent_ui_head('PHP Agent - offline PHP expert');
echo "<body>\n";
echo '<h1>PHP Agent</h1>';
echo '<p class="sub">Ask anything in PHP. ' . count($agent->all()) . ' curated topics, ' . $agent->index()->count() . ' built-in functions, PHP ' . php_agent_e($agent->index()->phpVersion()) . '. Offline, no key, no account.</p>';
echo '<p style="text-align:center"><a href="ai.php">AI box (Local / Gemini) &rarr;</a></p>';
php_agent_ui_search_form($agent, $query, 'index.php', false, 'local');
if ($result !== null) {
    php_agent_ui_render_result($agent, $result, $query);
}
echo '<p><small>Categories: ' . php_agent_e(implode(', ', $agent->categories())) . '</small></p>';
echo '<p><small>Function index generated by reflection on this PHP install. Regenerate on another install with <code>php tools/generate-function-index.php</code>.</small></p>';
php_agent_ui_scripts();
echo "</body></html>\n";

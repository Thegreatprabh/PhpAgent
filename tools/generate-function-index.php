<?php
// PhpAgent v2 - function-index generator.
// Generates data/all-functions.json from PHP reflection on THIS install.
// No hand-typed function list, no descriptions invented: every entry is
// name + extension + reflection signature + deprecation flag + php.net
// link + a link to a verified curated example, if one already exists.
// Run: php tools/generate-function-index.php [--out data/all-functions.json]
// Re-run on any PHP install to regenerate a complete index for THAT install
// (loaded extensions change the list). No network calls.

declare(strict_types=1);

$root = dirname(__DIR__);
$out = $argv[1] ?? ($argv[2] ?? null);
$outputPath = $root . '/data/all-functions.json';
foreach ($argv as $arg) {
    if (str_starts_with($arg, '--out=')) {
        $outputPath = substr($arg, 6);
    }
}

// Curated examples: map function name (lowercase) -> curated entry id.
$curated = [];
foreach (glob($root . '/data/*.json') ?: [] as $file) {
    if (in_array(basename($file), ['all-functions.json', 'language-constructs.json'], true)) {
        continue;
    }
    $decoded = json_decode((string) file_get_contents($file), true);
    if (!is_array($decoded)) {
        continue;
    }
    foreach ($decoded as $entry) {
        foreach ((array) ($entry['functions'] ?? []) as $fn) {
            $key = strtolower((string) $fn);
            if (!isset($curated[$key])) {
                $curated[$key] = (string) ($entry['id'] ?? '');
            }
        }
    }
}

/** Render a reflection type (named / union / intersection) as a string. */
function gen_type(?ReflectionType $type): string
{
    if ($type === null) {
        return '';
    }
    if ($type instanceof ReflectionNamedType) {
        $name = $type->getName();
        if ($type->isBuiltin()) {
            return ($type->allowsNull() && $name !== 'mixed' && $name !== 'null' ? '?' : '') . $name;
        }
        return ($type->allowsNull() && $name !== 'mixed' ? '?' : '') . '\\' . ltrim($name, '\\');
    }
    if ($type instanceof ReflectionUnionType) {
        $parts = [];
        foreach ($type->getTypes() as $inner) {
            $parts[] = gen_type($inner);
        }
        return implode('|', $parts);
    }
    if ($type instanceof ReflectionIntersectionType) {
        $parts = [];
        foreach ($type->getTypes() as $inner) {
            $parts[] = gen_type($inner);
        }
        return implode('&', $parts);
    }
    return (string) $type;
}

/** Render one parameter, safely. Reflection on internal functions can lack defaults. */
function gen_param(ReflectionParameter $param): string
{
    $out = '';
    $type = gen_type($param->getType());
    if ($type !== '') {
        $out .= $type . ' ';
    }
    if ($param->isPassedByReference()) {
        $out .= '&';
    }
    if ($param->isVariadic()) {
        $out .= '...';
    }
    $out .= '$' . $param->getName();
    if ($param->isVariadic()) {
        return $out;
    }
    if ($param->isOptional()) {
        if ($param->isDefaultValueAvailable()) {
            try {
                if ($param->isDefaultValueConstant()) {
                    $def = $param->getDefaultValueConstantName() ?? 'null';
                } else {
                    $def = var_export($param->getDefaultValue(), true);
                }
            } catch (Throwable $e) {
                $def = '...';
            }
            $out .= ' = ' . $def;
        } elseif ($param->allowsNull()) {
            $out .= ' = null';
        } else {
            $out .= ' = ...';
        }
    }
    return $out;
}

$names = get_defined_functions()['internal'] ?? [];
sort($names, SORT_STRING);
$functions = [];
foreach ($names as $name) {
    $ref = new ReflectionFunction($name);
    $params = [];
    foreach ($ref->getParameters() as $param) {
        $params[] = gen_param($param);
    }
    $return = gen_type($ref->getReturnType());
    $signature = ($return !== '' ? $return . ' ' : '') . $name . '(' . implode(', ', $params) . ')';
    $lower = strtolower($name);
    $functions[] = [
        'name' => $name,
        'extension' => $ref->getExtensionName() ?? 'Core',
        'signature' => $signature,
        'return_type' => $return,
        'is_deprecated' => $ref->isDeprecated(),
        'is_internal' => true,
        'url' => 'https://www.php.net/manual/en/function.' . str_replace('_', '-', $name) . '.php',
        'example_entry' => $curated[$lower] ?? null,
        'example' => null,
    ];
}

$payload = [
    'generated_at' => gmdate('Y-m-d\TH:i:s\Z'),
    'php_version' => PHP_VERSION,
    'extensions' => get_loaded_extensions(),
    'count' => count($functions),
    'note' => 'Generated by reflection on this PHP install. No descriptions were invented. Entries without a verified curated example have example=null. Re-run tools/generate-function-index.php on another install to regenerate for that install.',
    'functions' => $functions,
];

$json = json_encode($payload, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
if ($json === false) {
    fwrite(STDERR, "JSON encode failed.\n");
    exit(1);
}
file_put_contents($outputPath, $json . "\n");
echo 'Wrote ' . count($functions) . ' functions to ' . $outputPath . ' (PHP ' . PHP_VERSION . ")\n";
